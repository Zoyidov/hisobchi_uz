#!/usr/bin/env python3
"""Offline `flutter gen-l10n` o'rnini bosuvchi generator.

`flutter gen-l10n` bilan bir xil API chiqaradi (lib/core/localization/gen/),
shuning uchun Mac'da `flutter gen-l10n` ishga tushirilsa ham natija mos keladi.
Qo'llab-quvvatlanadi: oddiy matn, {placeholder} (String/int/num/double/Object),
va butun xabar bo'yicha ICU plural: "{count, plural, one{..} few{..} other{..}}".

Ishlatish:  python3 tool/gen_l10n.py
"""
import json, re, os, sys
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARB=os.path.join(ROOT,'lib/l10n'); OUT=os.path.join(ROOT,'lib/core/localization/gen')
TEMPLATE='uz'; LOCALES=['ru','uz']  # alphabetical, like flutter
def load(loc): return json.load(open(os.path.join(ARB,f'app_{loc}.arb'),encoding='utf-8'))
tpl=load(TEMPLATE)
keys=[k for k in tpl if not k.startswith('@')]
def esc(s): return s.replace('\\','\\\\').replace("'","\\'").replace('$','\\$').replace('\n','\\n')
def meta(k): return tpl.get('@'+k,{}) or {}
def params(k):
    ph=meta(k).get('placeholders',{}) or {}
    return [(n,(v or {}).get('type','Object')) for n,v in ph.items()]
PLURAL=re.compile(r'^\{(\w+),\s*plural,(.*)\}$',re.S)
def interp(text, names):
    out=[];i=0
    for m in re.finditer(r'\{(\w+)\}',text):
        out.append(esc(text[i:m.start()]))
        out.append('${'+m.group(1)+'}' if m.group(1) in names else esc(m.group(0)))
        i=m.end()
    out.append(esc(text[i:])); return "'"+''.join(out)+"'"
def plural_forms(body):
    forms={};i=0
    while i<len(body):
        m=re.match(r'\s*(=\d+|zero|one|two|few|many|other)\s*\{',body[i:])
        if not m: break
        j=i+m.end(); depth=1; k=j
        while depth: 
            if body[k]=='{': depth+=1
            elif body[k]=='}': depth-=1
            k+=1
        forms[m.group(1)]=body[j:k-1]; i=k
    return forms
NAMES={'=0':'zero','=1':'one','=2':'two','zero':'zero','one':'one','two':'two','few':'few','many':'many','other':'other'}
def body(k, text, loc):
    ps=params(k); names=[n for n,_ in ps]
    m=PLURAL.match(text.strip())
    if m:
        var=m.group(1); forms=plural_forms(m.group(2))
        args=', '.join(f"{NAMES[f]}: {interp(t.replace('#','{'+var+'}'),names)}" for f,t in forms.items())
        return f"    String _temp0 = intl.Intl.pluralLogic(\n      {var},\n      locale: localeName,\n      {args},\n    );\n    return _temp0;"
    return f"    return {interp(text,names)};"
def sig(k):
    ps=params(k)
    if not ps: return f"String get {k}"
    return f"String {k}(" + ', '.join(f"{'num' if t in ('num','double') and False else t} {n}" for n,t in ps) + ")"
# abstract
a=["import 'dart:async';","","import 'package:flutter/foundation.dart';","import 'package:flutter/widgets.dart';","import 'package:flutter_localizations/flutter_localizations.dart';","import 'package:intl/intl.dart' as intl;",""]
a+= [f"import 'app_localizations_{l}.dart';" for l in LOCALES]
a+=["","// ignore_for_file: type=lint","","/// Generated by tool/gen_l10n.py (API-compatible with `flutter gen-l10n`).","abstract class AppLocalizations {","  AppLocalizations(String locale)","    : localeName = intl.Intl.canonicalizedLocale(locale.toString());","","  final String localeName;","","  static AppLocalizations of(BuildContext context) {","    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;","  }","","  static const LocalizationsDelegate<AppLocalizations> delegate =","      _AppLocalizationsDelegate();","","  static const List<LocalizationsDelegate<dynamic>> localizationsDelegates =","      <LocalizationsDelegate<dynamic>>[","        delegate,","        GlobalMaterialLocalizations.delegate,","        GlobalCupertinoLocalizations.delegate,","        GlobalWidgetsLocalizations.delegate,","      ];","","  static const List<Locale> supportedLocales = <Locale>["]
a+=[f"    Locale('{l}')," for l in LOCALES]+["  ];",""]
for k in keys:
    d=meta(k).get('description')
    a.append(f"  /// {d if d else 'No description provided for @'+k+'.'}\n  ///\n  /// In {TEMPLATE}, this message translates to:\n  /// **'{tpl[k].replace(chr(10),' ')}'**\n  {sig(k)};\n")
a+=["}","","class _AppLocalizationsDelegate","    extends LocalizationsDelegate<AppLocalizations> {","  const _AppLocalizationsDelegate();","","  @override","  Future<AppLocalizations> load(Locale locale) {","    return SynchronousFuture<AppLocalizations>(lookupAppLocalizations(locale));","  }","","  @override","  bool isSupported(Locale locale) =>","      <String>["+', '.join(f"'{l}'" for l in LOCALES)+"].contains(locale.languageCode);","","  @override","  bool shouldReload(_AppLocalizationsDelegate old) => false;","}","","AppLocalizations lookupAppLocalizations(Locale locale) {","  // Lookup logic when only language code is specified.","  switch (locale.languageCode) {"]
for l in LOCALES: a+= [f"    case '{l}':",f"      return AppLocalizations{l.capitalize()}();"]
a+=["  }","","  throw FlutterError(","    'AppLocalizations.delegate failed to load unsupported locale \"$locale\". This is likely '","    'an issue with the localizations generation tool. Please file an issue '","    'on GitHub with a reproducible sample app and the gen-l10n configuration '","    'that was used.',","  );","}",""]
open(os.path.join(OUT,'app_localizations.dart'),'w',encoding='utf-8').write('\n'.join(a))
LANG={'ru':'Russian','uz':'Uzbek'}
errors=[]
for l in LOCALES:
    data=load(l)
    o=["// ignore: unused_import","import 'package:intl/intl.dart' as intl;","import 'app_localizations.dart';","","// ignore_for_file: type=lint","",f"/// The translations for {LANG[l]} (`{l}`).",f"class AppLocalizations{l.capitalize()} extends AppLocalizations {{",f"  AppLocalizations{l.capitalize()}([String locale = '{l}']) : super(locale);",""]
    for k in keys:
        if k not in data: errors.append(f'{l}: missing {k}'); text=tpl[k]
        else: text=data[k]
        ps=params(k)
        if not ps and not PLURAL.match(text.strip()):
            o.append(f"  @override\n  String get {k} => {interp(text,[])};\n")
        else:
            o.append(f"  @override\n  {sig(k)} {{\n{body(k,text,l)}\n  }}\n")
    extra=[k for k in data if not k.startswith('@') and k not in tpl]
    if extra: errors.append(f'{l}: unknown keys {extra[:5]}')
    o.append("}")
    open(os.path.join(OUT,f'app_localizations_{l}.dart'),'w',encoding='utf-8').write('\n'.join(o)+'\n')
if errors:
    print('\n'.join(errors)); sys.exit(1)
print(f'{len(keys)} keys generated for {LOCALES}')
